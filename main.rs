// OUTPUT — СОХРАНЕНИЕ И КОПИРОВАНИЕ
// ============================================================

// Сохранение изображения в Pictures/RustShot.
//
// Возвращаем Result<PathBuf, String>.
//
// PathBuf — владеющий тип пути.
// В отличие от &Path, он может хранить и изменять путь.
//
// Возвращаем путь пользователю, чтобы можно было вывести,
// куда именно был сохранён скриншот.
fn save_image(image: &RgbaImage) -> Result<PathBuf, String> {

    // dirs::picture_dir() пытается определить стандартную
    // директорию изображений пользователя.
    //
    // unwrap_or_else вызывается только в случае None.
    //
    // Если директорию Pictures определить не удалось,
    // используем /tmp.
    //
    // Это лучше, чем panic, потому что отсутствие стандартной
    // директории не обязательно должно завершать программу.
    let directory = dirs::picture_dir()
        .unwrap_or_else(|| PathBuf::from("/tmp"))
        .join("RustShot");


    // create_dir_all создаёт директорию и все отсутствующие
    // родительские директории.
    //
    // Например, если Pictures/RustShot ещё нет,
    // функция создаст её.
    //
    // map_err преобразует системную ошибку в String.
    std::fs::create_dir_all(&directory)
        .map_err(|e| e.to_string())?;


    // Формируем имя файла на основе текущего времени.
    //
    // format! создаёт новую String.
    //
    // Формат:
    // rustshot_2026-11-01_21-30-00.png
    //
    // Это помогает избежать перезаписи старых скриншотов
    // при обычном использовании программы.
    let filename = format!(
        "rustshot_{}.png",
        Local::now().format("%Y-%m-%d_%H-%M-%S")
    );


    // join объединяет путь к директории и имя файла.
    //
    // Не нужно вручную добавлять "/" — PathBuf сам учитывает
    // правила построения путей операционной системы.
    let path = directory.join(filename);


    // save определяет формат изображения по расширению файла.
    //
    // В нашем случае это PNG.
    image.save(&path).map_err(|e| e.to_string())?;


    // Возвращаем готовый путь.
    //
    // Ok означает успешное завершение операции.
    Ok(path)
}


// Копирование изображения в системный буфер обмена.
fn copy_image(image: &RgbaImage) -> Result<(), String> {

    // Создаём объект Clipboard.
    //
    // new() может вернуть ошибку, например, если системный
    // буфер обмена недоступен.
    //
    // ? прекращает выполнение функции при ошибке.
    Clipboard::new()
        .map_err(|e| e.to_string())?


        // Передаём изображение в буфер обмена.
        //
        // ImageData содержит:
        // width  — ширину;
        // height — высоту;
        // bytes  — пиксельный буфер.
        .set_image(ImageData {

            // arboard использует usize для размеров.
            // Поэтому преобразуем u32 в usize.
            width: image.width() as usize,
            height: image.height() as usize,


            // Cow::Owned означает, что передаём собственный Vec<u8>.
            //
            // as_raw() возвращает ссылку на исходный пиксельный буфер.
            //
            // clone() создаёт его копию.
            //
            // Почему копируем?
            //
            // Потому что Clipboard должен получить данные,
            // которые будут жить независимо от image.
            //
            // Мы не можем безопасно передать ему временную ссылку
            // на внутренний буфер изображения.
            bytes: Cow::Owned(image.as_raw().clone()),
        })

        // set_image тоже может завершиться ошибкой.
        .map_err(|e| e.to_string())
}


// ============================================================
// APPLICATION METHODS — МЕТОДЫ RUSTSHOT
// ============================================================

// impl — блок реализации методов для определённого типа.
//
// Здесь мы описываем поведение RustShot.
//
// В отличие от обычных функций, методы получают доступ к состоянию
// структуры через self.
impl RustShot {

    // Конструктор приложения.
    //
    // new — общепринятое название функции, создающей новый объект.
    //
    // &egui::Context — неизменяемая ссылка на контекст egui.
    // image — передаётся по значению, то есть RustShot получает владение.
    // mode и destination копируются, потому что реализуют Copy.
    fn new(
        ctx: &egui::Context,
        image: RgbaImage,
        mode: Mode,
        destination: Destination,
    ) -> Self {

        // egui использует ColorImage для загрузки изображения
        // в графическую подсистему.
        //
        // from_rgba_unmultiplied принимает:
        // [ширина, высота] и пиксельный буфер RGBA.
        //
        // Unmultiplied означает, что RGB-каналы не умножены
        // на альфа-канал заранее.
        let color_image = egui::ColorImage::from_rgba_unmultiplied(
            [image.width() as usize, image.height() as usize],
            image.as_raw(),
        );


        // Загружаем изображение как текстуру.
        //
        // load_texture возвращает TextureHandle.
        //
        // TextureHandle — это не сами пиксели, а дескриптор ресурса,
        // который позволяет egui отображать текстуру.
        //
        // LINEAR задаёт линейную фильтрацию при масштабировании.
        // Для обычного скриншота это даёт более плавное отображение.
        let texture = ctx.load_texture(
            "rustshot",
            color_image,
            egui::TextureOptions::LINEAR,
        );


        // Self означает тип, внутри которого мы сейчас находимся.
        //
        // Здесь Self — это RustShot.
        //
        // Мы создаём объект и заполняем все его поля.
        Self {
            image,
            texture,
            mode,
            destination,


            // Начальный инструмент зависит от режима.
            //
            // В режиме Area логично сразу начать с выделения.
            //
            // В режиме Full выделение не требуется,
            // поэтому сразу выбираем пикселизацию.
            tool: if mode == Mode::Area {
                Tool::Select
            } else {
                Tool::Blur
            },


            // Пока пользователь ничего не выделил.
            selection: None,

            // Перетаскивание ещё не началось.
            drag_start: None,

            // Вектор пока пуст.
            blur_areas: Vec::new(),

            // Начальное сообщение интерфейса.
            status: "Ready".into(),
        }
    }


    // Закрытие окна.
    //
    // &self означает, что метод только читает объект.
    // Изменять поля RustShot ему не разрешено.
    //
    // ctx.send_viewport_cmd отправляет команду оконной системе.
    fn close(&self, ctx: &egui::Context) {
        ctx.send_viewport_cmd(ViewportCommand::Close);
    }


    // Завершение редактирования и вывод результата.
    //
    // &mut self нужен, потому что при ошибке мы меняем status,
    // а также можем завершить работу окна.
    //
    // ctx передаётся по ссылке, поскольку нам не нужно
    // владеть контекстом egui.
    fn finish(&mut self, ctx: &egui::Context) {

        // Сначала формируем итоговое изображение.
        //
        // match позволяет обработать оба варианта Result:
        // Ok(image) и Err(error).
        let result = match render_result(self) {

            Ok(image) => image,

            // При ошибке не закрываем приложение.
            //
            // Вместо этого показываем сообщение в интерфейсе,
            // чтобы пользователь мог исправить ситуацию.
            Err(error) => {
                self.status = error;
                return;
            }
        };


        // Теперь выбираем способ вывода.
        //
        // Destination — enum, поэтому match заставляет нас
        // явно обработать все варианты.
        let output = match self.destination {

            // map преобразует успешный результат copy_image
            // в текстовое сообщение.
            //
            // Result<(), String> превращается в Result<String, String>.
            Destination::Clipboard => {
                copy_image(&result)
                    .map(|_| "Copied to clipboard".to_string())
            }

            Destination::Pictures => {
                save_image(&result)
                    .map(|p| format!("Saved: {}", p.display()))
            }
        };


        // Обрабатываем итог операции.
        match output {

            // Если копирование или сохранение прошло успешно:
            Ok(message) => {

                // println! выводит информацию в терминал.
                println!("RustShot: {message}");

                // Закрываем окно.
                self.close(ctx);
            }

            // Если произошла ошибка, оставляем окно открытым.
            Err(error) => {
                self.status = error;
            }
        }
    }


    // Переключение инструмента.
    //
    // tool передаётся по значению, потому что Tool реализует Copy.
    fn set_tool(&mut self, tool: Tool) {

        // Изменяем активный инструмент.
        self.tool = tool;


        // Меняем сообщение состояния.
        //
        // match здесь используется для получения текста,
        // соответствующего выбранному инструменту.
        self.status = match tool {
            Tool::Select => "Selection tool".into(),
            Tool::Blur => "Blur tool".into(),
        };
    }
}


// ============================================================
// HUD — ИНТЕРФЕЙСНЫЕ ПОДСКАЗКИ
// ============================================================

// Painter — инструмент egui для рисования фигур и текста.
//
// &egui::Painter:
// мы получаем ссылку на Painter, а не забираем его.
//
// &RustShot:
// функция только читает состояние приложения.
fn draw_hud(painter: &egui::Painter, app: &RustShot) {

    // Текст подсказок зависит от режима.
    //
    // В Area доступно переключение между Select и Blur.
    //
    // В Full инструмент Select не используется.
    let controls = if app.mode == Mode::Area {
        "1 SELECT   2 BLUR   |   ENTER FINISH   ESC CANCEL"
    } else {
        "2 BLUR   |   ENTER FINISH   ESC CANCEL"
    };


    // Создаём прямоугольник HUD.
    //
    // from_min_size принимает:
    // начальную позицию и размер.
    let rect = Rect::from_min_size(
        Pos2::new(18.0, 18.0),
        Vec2::new(480.0, 40.0),
    );


    // Рисуем тёмный фон.
    //
    // 210 — прозрачность/альфа-канал.
    // Чем выше значение, тем менее прозрачный фон.
    painter.rect_filled(
        rect,
        7.0,
        Color32::from_black_alpha(210),
    );


    // Рисуем фиолетовую рамку.
    //
    // Stroke::new:
    // 1. Толщина линии.
    // 2. Цвет линии.
    //
    // StrokeKind::Inside означает, что обводка рисуется
    // внутри границ прямоугольника.
    painter.rect_stroke(
        rect,
        7.0,
        Stroke::new(1.0_f32, PURPLE),
        egui::StrokeKind::Inside,
    );


    // Рисуем текст подсказок.
    //
    // center() возвращает центр прямоугольника.
    //
    // CENTER_CENTER выравнивает текст по центру
    // как горизонтально, так и вертикально.
    painter.text(
        rect.center(),
        egui::Align2::CENTER_CENTER,
        controls,
        egui::FontId::proportional(13.0),
        Color32::WHITE,
    );


    // Показываем сообщение состояния, если оно не пустое.
    //
    // is_empty() возвращает true, если String не содержит символов.
    if !app.status.is_empty() {

        painter.text(
            Pos2::new(20.0, 70.0),
            egui::Align2::LEFT_TOP,
            &app.status,
            egui::FontId::proportional(13.0),
            PURPLE,
        );
    }
}


// ============================================================
// GUI UPDATE — ГЛАВНЫЙ ЦИКЛ ИНТЕРФЕЙСА
// ============================================================

// Реализуем трейт eframe::App.
//
// Trait — это набор методов, которые тип должен реализовать,
// чтобы соответствовать определённому интерфейсу.
//
// eframe::App требует метод update.
//
// eframe вызывает update при необходимости обновить интерфейс.
//
// Поэтому именно здесь мы:
// - обрабатываем клавиатуру;
// - обрабатываем мышь;
// - рисуем скриншот;
// - рисуем выделения;
// - рисуем подсказки.
impl eframe::App for RustShot {

    fn update(
        &mut self,
        ctx: &egui::Context,
        _frame: &mut eframe::Frame,
    ) {

        // Флаги действий текущего кадра.
        //
        // Они нужны, чтобы сначала прочитать состояние клавиатуры,
        // а затем выполнить действия.
        //
        // mut необходим, потому что значения будут изменяться.
        let mut finish = false;
        let mut close = false;


        // ctx.input получает доступ к текущему состоянию ввода.
        //
        // Внутри closure мы читаем нажатия клавиш.
        //
        // Почему используется замыкание?
        //
        // egui управляет доступом к состоянию ввода.
        // Замыкание позволяет выполнить чтение внутри контролируемого
        // egui контекста, не забирая сам объект ввода наружу.
        ctx.input(|input| {

            // key_pressed возвращает true только в момент нажатия.
            //
            // Это не то же самое, что key_down:
            // key_down остаётся true, пока клавиша удерживается.
            close = input.key_pressed(egui::Key::Escape);
            finish = input.key_pressed(egui::Key::Enter);


            // Клавиша 1 включает выделение.
            //
            // Проверяем mode, потому что в Full нет смысла
            // переключаться на инструмент Select.
            if input.key_pressed(egui::Key::Num1)
                && self.mode == Mode::Area
            {
                self.set_tool(Tool::Select);
            }


            // Клавиша 2 включает пикселизацию.
            if input.key_pressed(egui::Key::Num2) {
                self.set_tool(Tool::Blur);
            }
        });


        // Сначала обрабатываем закрытие.
        //
        // return завершает текущий вызов update.
        //
        // Это важно: после закрытия не нужно продолжать
        // обрабатывать мышь и рисовать интерфейс.
        if close {
            self.close(ctx);
            return;
        }


        // Затем обрабатываем завершение.
        if finish {
            self.finish(ctx);
            return;
        }


        // ====================================================
        // CENTRAL PANEL — ОБЛАСТЬ РИСОВАНИЯ
        // ====================================================

        // CentralPanel занимает центральную область окна.
        //
        // Frame::NONE убирает стандартное оформление панели,
        // потому что мы хотим показывать только снимок экрана.
        egui::CentralPanel::default()
            .frame(egui::Frame::NONE)
            .show(ctx, |ui| {

                // Получаем доступную область интерфейса.
                let available = ui.max_rect();


                // Получаем исходный размер изображения.
                //
                // Размеры изображения u32, но egui использует f32
                // для геометрии интерфейса.
                let size = Vec2::new(
                    self.image.width() as f32,
                    self.image.height() as f32,
                );


                // Вычисляем коэффициент масштабирования.
                //
                // Сначала считаем, насколько изображение можно
                // увеличить по ширине.
                //
                // Затем считаем ограничение по высоте.
                //
                // min выбирает меньшее значение, чтобы изображение
                // целиком помещалось в доступную область.
                //
                // Благодаря этому мы сохраняем пропорции изображения.
                let scale = (
                    available.width() / size.x
                )
                .min(
                    available.height() / size.y
                );


                // Создаём прямоугольник изображения.
                //
                // from_center_size центрирует его в доступной области.
                //
                // size * scale изменяет размеры с сохранением пропорций.
                let canvas = Rect::from_center_size(
                    available.center(),
                    size * scale,
                );


                // Painter используется для рисования.
                //
                // Он будет использоваться ниже для:
                // - изображения;
                // - затемнения;
                // - границ выделения;
                // - областей пикселизации;
                // - HUD.
                let painter = ui.painter();


                // Отображаем текстуру.
                //
                // texture.id() возвращает идентификатор GPU-текстуры.
                //
                // canvas определяет, где и какого размера её рисовать.
                //
                // Последний Rect задаёт область текстуры:
                // от (0, 0) до (1, 1) — вся текстура целиком.
                //
                // Color32::WHITE означает отсутствие дополнительного
                // цветового затемнения текстуры.
                painter.image(
                    self.texture.id(),
                    canvas,
                    Rect::from_min_max(
                        Pos2::ZERO,
                        Pos2::new(1.0, 1.0),
                    ),
                    Color32::WHITE,
                );


                // =================================================
                // MOUSE INPUT — ОБРАБОТКА МЫШИ
                // =================================================

                // ui.interact связывает прямоугольник canvas
                // с обработчиком взаимодействия.
                //
                // Id::new создаёт идентификатор элемента.
                //
                // ID нужен egui, чтобы отличать этот элемент
                // от других интерактивных элементов интерфейса.
                //
                // Sense::click_and_drag разрешает:
                // - нажатия;
                // - перетаскивание.
                let response = ui.interact(
                    canvas,
                    Id::new("canvas"),
                    Sense::click_and_drag(),
                );


                // Получаем позицию мыши внутри интерактивного элемента.
                //
                // Option<Pos2>:
                // Some(pos) — мышь находится над элементом;
                // None      — позиции нет.
                let pointer = response.interact_pointer_pos();


                // Пользователь начал перетаскивание.
                if response.drag_started() {

                    // if let — удобный способ обработать Some,
                    // не используя полный match.
                    //
                    // Если pointer == None, блок просто пропускается.
                    if let Some(pos) = pointer {

                        // Запоминаем начальную координату.
                        //
                        // Важно: сохраняем её в координатах изображения,
                        // а не GUI.
                        //
                        // Тогда при изменении масштаба отображения
                        // геометрия выделения остаётся связанной
                        // с исходными пикселями.
                        self.drag_start = Some(
                            to_image(pos, canvas, &self.image)
                        );
                    }
                }


                // Пока мышь удерживается и перемещается.
                if response.dragged() {

                    // Для работы нужны и начало, и текущая позиция.
                    //
                    // Если одно из значений отсутствует,
                    // операция не выполняется.
                    if let (Some(start), Some(pos)) = (
                        self.drag_start,
                        pointer,
                    ) {

                        // В режиме Select обновляем выделение
                        // прямо во время перетаскивания.
                        //
                        // Это позволяет показывать пользователю
                        // предварительный результат выделения.
                        if self.tool == Tool::Select {

                            self.selection = Some(
                                Rect::from_two_pos(
                                    start,
                                    to_image(pos, canvas, &self.image),
                                )
                            );
                        }
                    }
                }


                // Мышь отпущена, перетаскивание завершено.
                if response.drag_stopped() {

                    // take() извлекает значение из Option
                    // и заменяет исходное значение на None.
                    //
                    // Например:
                    //
                    // drag_start = Some(pos)
                    // drag_start.take()
                    //
                    // Результат: Some(pos),
                    // а drag_start теперь снова None.
                    //
                    // Это удобно, потому что после завершения
                    // перетаскивания начальная позиция больше не нужна.
                    if let (Some(start), Some(pos)) = (
                        self.drag_start.take(),
                        pointer,
                    ) {

                        let end = to_image(
                            pos,
                            canvas,
                            &self.image,
                        );

                        // from_two_pos создаёт прямоугольник
                        // между двумя точками.
                        //
                        // Порядок точек не имеет значения:
                        // можно тянуть мышь в любую сторону.
                        let rect = Rect::from_two_pos(start, end);


                        // Действие зависит от активного инструмента.
                        match self.tool {

                            // Select работает только в Area.
                            Tool::Select if self.mode == Mode::Area => {
                                self.selection = Some(rect);
                                self.status = "Area selected".into();
                            }

                            // Blur добавляет новую область в Vec.
                            //
                            // push добавляет элемент в конец массива.
                            Tool::Blur => {
                                self.blur_areas.push(rect);
                                self.status = "Blur area added".into();
                            }

                            // Остальные варианты ничего не делают.
                            _ => {}
                        }
                    }
                }


                // =================================================
                // SELECTION OVERLAY — ОТОБРАЖЕНИЕ ВЫДЕЛЕНИЯ
                // =================================================

                // Если selection содержит Some(Rect),
                // рисуем выделенную область.
                //
                // Если None — блок не выполняется.
                if let Some(selection) = self.selection {

                    // Переводим координаты выделения обратно в GUI.
                    //
                    // Это необходимо, потому что selection хранится
                    // в координатах исходного изображения.
                    let selected = Rect::from_two_pos(
                        to_screen(selection.min, canvas, &self.image),
                        to_screen(selection.max, canvas, &self.image),
                    );


                    // Цвет затемнения.
                    let dim = Color32::from_black_alpha(155);


                    // Затемняем всё вокруг выделенной области.
                    //
                    // Почему четыре прямоугольника?
                    //
                    // Вместо создания отдельного сложного объекта
                    // маски мы рисуем четыре простые области:
                    //
                    // 1. Над выделением.
                    // 2. Под выделением.
                    // 3. Слева от выделения.
                    // 4. Справа от выделения.
                    //
                    // В результате выделенная часть остаётся яркой,
                    // а остальной экран затемняется.
                    for area in [

                        // Верхняя область.
                        Rect::from_min_max(
                            canvas.min,
                            Pos2::new(canvas.max.x, selected.min.y),
                        ),

                        // Нижняя область.
                        Rect::from_min_max(
                            Pos2::new(canvas.min.x, selected.max.y),
                            canvas.max,
                        ),

                        // Левая область.
                        Rect::from_min_max(
                            Pos2::new(canvas.min.x, selected.min.y),
                            Pos2::new(selected.min.x, selected.max.y),
                        ),

                        // Правая область.
                        Rect::from_min_max(
                            Pos2::new(selected.max.x, selected.min.y),
                            Pos2::new(canvas.max.x, selected.max.y),
                        ),
                    ] {

                        // Рисуем каждую область затемнения.
                        painter.rect_filled(
                            area,
                            0.0,
                            dim,
                        );
                    }


                    // Рисуем фиолетовую границу выделения.
                    painter.rect_stroke(
                        selected,
                        0.0,
                        Stroke::new(2.0_f32, PURPLE),
                        egui::StrokeKind::Inside,
                    );
                }


                // =================================================
                // BLUR AREAS — ПРЕДПРОСМОТР ПИКСЕЛИЗАЦИИ
                // =================================================

                // Перебираем все добавленные области пикселизации.
                //
                // Мы не обрабатываем изображение прямо здесь.
                // Здесь рисуется только визуальная подсказка.
                //
                // Настоящая пикселизация выполняется в render_result()
                // непосредственно перед сохранением или копированием.
                for area in &self.blur_areas {

                    // Переводим координаты изображения в координаты GUI.
                    let rect = Rect::from_two_pos(
                        to_screen(area.min, canvas, &self.image),
                        to_screen(area.max, canvas, &self.image),
                    );


                    // Полупрозрачный тёмный фон области.
                    painter.rect_filled(
                        rect,
                        0.0,
                        Color32::from_black_alpha(140),
                    );


                    // Голубая граница области.
                    painter.rect_stroke(
                        rect,
                        0.0,
                        Stroke::new(2.0_f32, Color32::LIGHT_BLUE),
                        egui::StrokeKind::Inside,
                    );
                }


                // =================================================
                // CURRENT BLUR PREVIEW — ТЕКУЩЕЕ ПЕРЕТАСКИВАНИЕ
                // =================================================

                // Если активен Blur, показываем прямоугольник,
                // пока пользователь тянет мышь.
                //
                // В отличие от blur_areas, эта область ещё
                // не добавлена в постоянный список.
                if self.tool == Tool::Blur {

                    if let (Some(start), Some(pos)) = (
                        self.drag_start,
                        pointer,
                    ) {

                        // start находится в координатах изображения.
                        // Поэтому переводим его в GUI.
                        //
                        // pos уже получен из egui и находится
                        // в координатах интерфейса.
                        let rect = Rect::from_two_pos(
                            to_screen(start, canvas, &self.image),
                            pos,
                        );


                        // Рисуем только границу текущей области.
                        painter.rect_stroke(
                            rect,
                            0.0,
                            Stroke::new(2.0_f32, Color32::LIGHT_BLUE),
                            egui::StrokeKind::Inside,
                        );
                    }
                }


                // =================================================
                // HUD — ПОДСКАЗКИ
                // =================================================

                // Рисуем HUD последним, чтобы он отображался
                // поверх изображения, выделения и областей Blur.
                draw_hud(painter, self);
            });
    }
}


// ============================================================
// MAIN — ТОЧКА ВХОДА В ПРОГРАММУ
// ============================================================

// main — функция, с которой начинается выполнение Rust-программы.
//
// eframe::Result<()> означает:
// программа может вернуть ошибку eframe,
// а при успехе не возвращает полезного значения.
fn main() -> eframe::Result<()> {

    // Сначала разбираем аргументы командной строки.
    let (mode, destination) = match parse_args() {

        Ok(args) => args,

        Err(error) => {

            // eprintln! выводит сообщение в stderr,
            // а не в обычный stdout.
            //
            // stderr предназначен для ошибок и диагностических сообщений.
            eprintln!("RustShot: {error}");
            eprintln!("Use: rustshot --area|--full --clipboard|--pictures");


            // exit(2) завершает программу с кодом ошибки.
            //
            // Код 2 условно обозначает неправильное использование
            // программы или аргументов командной строки.
            std::process::exit(2);
        }
    };


    // Захватываем экран до запуска GUI.
    //
    // Это принципиально важно:
    //
    // Если бы мы сначала открыли полноэкранный overlay,
    // а потом сделали скриншот, на снимке мог бы оказаться
    // сам RustShot.
    //
    // expect() завершает программу с сообщением,
    // если захват экрана не удался.
    //
    // Для простоты здесь используем expect,
    // но в дальнейшем можно заменить его на полноценную обработку ошибки.
    let image = capture_screen().expect("Screen capture failed");


    // Выводим размеры захваченного изображения.
    println!(
        "RustShot: {}x{}",
        image.width(),
        image.height(),
    );


    // ========================================================
    // WINDOW OPTIONS — НАСТРОЙКА ОКНА
    // ========================================================

    let options = eframe::NativeOptions {

        // ViewportBuilder настраивает окно приложения.
        viewport: egui::ViewportBuilder::default()

            // Название окна.
            .with_title("RustShot")

            // Отключаем стандартную рамку окна.
            //
            // Это нужно для полноэкранного overlay,
            // который должен выглядеть как единый слой поверх рабочего стола.
            .with_decorations(false)

            // Включаем полноэкранный режим.
            .with_fullscreen(true)

            // Просим оконную систему держать окно поверх остальных.
            .with_always_on_top(),

        // ..Default::default() — синтаксис обновления структуры.
        //
        // Мы задаём только нужное поле viewport,
        // а остальные поля NativeOptions получают значения по умолчанию.
        //
        // Это удобнее, чем вручную перечислять все поля структуры.
        ..Default::default()
    };


    // ========================================================
    // START GUI
    // ========================================================

    // run_native запускает нативное окно приложения.
    //
    // Первый аргумент — имя приложения.
    // Второй — настройки окна.
    // Третий — функция создания приложения.
    //
    // Box::new создаёт замыкание в куче.
    //
    // move означает, что замыкание забирает необходимые значения
    // из окружающей области видимости.
    //
    // Это важно, потому что создание приложения происходит
    // внутри callback-функции eframe.
    //
    // image, mode и destination должны быть доступны внутри неё.
    eframe::run_native(
        "RustShot",
        options,

        Box::new(move |cc| {

            // cc содержит CreationContext.
            // Из него мы получаем контекст egui.
            //
            // RustShot::new создаёт состояние приложения,
            // загружает текстуру и сохраняет настройки.
            //
            // Box::new помещает объект приложения в Box.
            //
            // Box<T> — умный указатель на значение в куче.
            // eframe ожидает такой объект, чтобы управлять
            // временем жизни приложения самостоятельно.
            Ok(Box::new(
                RustShot::new(
                    &cc.egui_ctx,
                    image,
                    mode,
                    destination,
                )
            ))
        }),
    )
}

