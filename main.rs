// struct объединяет несколько связанных значений в один тип.
//
// RustShot хранит всё состояние нашего приложения:
//
// - изображение;
// - GPU-текстуру для отображения;
// - режим работы;
// - способ сохранения;
// - выбранный инструмент;
// - выделение;
// - начало перетаскивания;
// - области пикселизации;
// - сообщение для пользователя.
//
// Почему мы храним это в одной структуре?
//
// Потому что все эти данные относятся к одному приложению.
// Благодаря этому методы RustShot могут работать с общим состоянием,
// а нам не нужно передавать десятки отдельных аргументов между функциями.
//
// Важно: поля структуры не являются автоматически публичными.
// Здесь они доступны внутри текущего модуля.
struct RustShot {

    // Исходный снимок экрана.
    //
    // RgbaImage владеет памятью с пикселями изображения.
    //
    // Мы сохраняем оригинал отдельно и не изменяем его при рисовании
    // предварительного просмотра.
    //
    // Благодаря этому можно повторно сформировать результат
    // из исходного изображения, не накапливая артефакты обработки.
    image: RgbaImage,

    // TextureHandle — дескриптор текстуры, загруженной в GUI.
    //
    // Само изображение находится в обычной оперативной памяти,
    // а текстура используется графической подсистемой для отображения.
    //
    // Это два разных представления одних и тех же визуальных данных.
    texture: egui::TextureHandle,


    // Настройки текущей сессии.
    mode: Mode,
    destination: Destination,
    tool: Tool,


    // Option<T> означает, что значение может существовать,
    // а может отсутствовать.
    //
    // Option<Rect> имеет два варианта:
    //
    // Some(rect) — область уже выбрана.
    // None       — пользователь ещё ничего не выделил.
    //
    // Это лучше, чем использовать Rect::ZERO как признак отсутствия,
    // потому что пустой прямоугольник и отсутствие значения —
    // разные понятия.
    selection: Option<Rect>,


    // Начальная координата перетаскивания мыши.
    //
    // None означает, что пользователь сейчас не рисует область.
    // Some(pos) означает, что перетаскивание началось.
    //
    // Мы храним начало отдельно, чтобы на каждом кадре вычислять
    // прямоугольник между начальной и текущей координатой мыши.
    drag_start: Option<Pos2>,


    // Vec<Rect> — динамический массив прямоугольников.
    //
    // Каждый Rect описывает область, которую нужно пикселизировать.
    //
    // Vec удобен здесь, потому что пользователь может добавить
    // произвольное количество областей во время работы.
    blur_areas: Vec<Rect>,


    // Строка состояния интерфейса.
    //
    // String — строка с принадлежащей ей памятью.
    // В отличие от &str, она может изменяться во время выполнения.
    status: String,
}


// ============================================================
// ARGUMENT PARSING — ОБРАБОТКА АРГУМЕНТОВ КОМАНДНОЙ СТРОКИ
// ============================================================

// Result<T, E> — стандартный тип Rust для операций,
// которые могут завершиться ошибкой.
//
// Здесь:
//
// Ok((Mode, Destination)) — аргументы разобраны успешно.
// Err(String)             — возникла ошибка.
//
// Почему не используем panic!?
//
// Ошибка аргументов — обычная ситуация, а не авария программы.
// Например, пользователь может забыть указать --area.
// Поэтому лучше вернуть понятное сообщение, чем аварийно завершаться.
fn parse_args() -> Result<(Mode, Destination), String> {

    // None означает, что пользователь пока не указал режим.
    //
    // Тип Option<Mode> выводится компилятором из дальнейшего использования.
    let mut mode = None;

    // Аналогично для назначения результата.
    let mut destination = None;


    // env::args() возвращает аргументы командной строки.
    //
    // Первый аргумент обычно является путём к исполняемому файлу.
    //
    // skip(1) пропускает его, потому что нас интересуют только параметры:
    //
    // --area
    // --full
    // --clipboard
    // --pictures
    for arg in env::args().skip(1) {

        // as_str() даёт строковое представление аргумента.
        // match сравнивает его с известными вариантами.
        match arg.as_str() {

            "--area" => {

                // Option::replace заменяет значение и возвращает старое.
                //
                // Например:
                // mode = None
                // mode.replace(Mode::Area)
                //
                // Теперь mode содержит Some(Mode::Area),
                // а результат операции — None.
                //
                // Если до этого режим уже был указан, replace вернёт Some.
                //
                // Так мы обнаруживаем конфликт:
                // --area --full
                if mode.replace(Mode::Area).is_some() {
                    return Err("Choose only --area or --full".into());
                }
            }

            "--full" => {
                if mode.replace(Mode::Full).is_some() {
                    return Err("Choose only --area or --full".into());
                }
            }

            "--clipboard" => {
                if destination.replace(Destination::Clipboard).is_some() {
                    return Err("Choose only --clipboard or --pictures".into());
                }
            }

            "--pictures" => {
                if destination.replace(Destination::Pictures).is_some() {
                    return Err("Choose only --clipboard or --pictures".into());
                }
            }

            // Справка.
            //
            // std::process::exit(0) немедленно завершает программу.
            // Код 0 означает успешное завершение.
            "--help" | "-h" => {
                println!(
                    "RustShot

Usage:
  rustshot --area --clipboard
  rustshot --area --pictures
  rustshot --full --clipboard
  rustshot --full --pictures

Options:
  --area       Select screenshot area
  --full       Capture entire screen
  --clipboard  Copy to clipboard
  --pictures   Save to Pictures/RustShot
  --help       Show help"
                );

                std::process::exit(0);
            }

            // unknown — это любое значение, которое не подошло
            // ни под один вариант match.
            //
            // {unknown} — форматирование переменной внутри строки.
            unknown => return Err(format!("Unknown argument: {unknown}")),
        }
    }


    // Возвращаем кортеж из двух значений.
    //
    // mode.ok_or(...) преобразует:
    //
    // Some(value) -> Ok(value)
    // None        -> Err(error)
    //
    // destination.unwrap_or(...) задаёт значение по умолчанию.
    //
    // Если пользователь не указал --clipboard или --pictures,
    // автоматически используем Pictures.
    //
    // В результате функция возвращает Result с кортежем:
    // (Mode, Destination).
    Ok((
        mode.ok_or("Specify --area or --full")?,
        destination.unwrap_or(Destination::Pictures),
    ))
}


// ============================================================
// SCREEN CAPTURE — ЗАХВАТ ЭКРАНА
// ============================================================

fn capture_screen() -> Result<RgbaImage, String> {

    // Screen::all() возвращает список доступных мониторов.
    //
    // map_err преобразует ошибку библиотеки screenshots
    // в String, который используется нашим приложением.
    //
    // ? — оператор раннего возврата ошибки.
    //
    // Если Screen::all() вернул Err, функция сразу завершится
    // с этой ошибкой.
    let screen = Screen::all()
        .map_err(|e| e.to_string())?

        // into_iter() превращает коллекцию в итератор,
        // который передаёт элементы по одному.
        //
        // next() берёт первый элемент.
        //
        // Здесь мы пока захватываем только первый монитор.
        .into_iter()
        .next()

        // Если список пустой, возвращаем понятную ошибку.
        .ok_or("No screen found")?;


    // Захватываем содержимое выбранного монитора.
    //
    // capture() возвращает изображение, которым владеет библиотека.
    // map_err преобразует возможную ошибку в String.
    let image = screen.capture().map_err(|e| e.to_string())?;


    // from_raw создаёт RgbaImage из сырых байтов пикселей.
    //
    // Нам нужно передать:
    // 1. Ширину.
    // 2. Высоту.
    // 3. Буфер пикселей.
    //
    // into_raw() забирает исходный буфер из image.
    //
    // Здесь происходит передача владения буфером.
    // После into_raw() прежний объект image больше не используется.
    //
    // from_raw возвращает Option<RgbaImage>, потому что размер буфера
    // может не соответствовать ожидаемому количеству пикселей.
    //
    // Например, RGBA требует 4 байта на один пиксель.
    RgbaImage::from_raw(
        image.width(),
        image.height(),
        image.into_raw(),
    )
    .ok_or("Invalid screenshot buffer".into())
}


// ============================================================
// COORDINATE CONVERSION — ПРЕОБРАЗОВАНИЕ КООРДИНАТ
// ============================================================

// В RustShot существуют две системы координат:
//
// 1. Координаты GUI — положение мыши в окне egui.
// 2. Координаты изображения — положение пикселя в RgbaImage.
//
// Они отличаются, потому что изображение может масштабироваться
// под размер окна.
//
// Например:
// Изображение имеет размер 1920x1080.
// На экране оно отображается в размере 1280x720.
//
// Если пользователь нажал мышью на X=640 в GUI,
// соответствующая координата изображения будет X=960.
//
// Эта функция переводит координату GUI в координату изображения.
fn to_image(pos: Pos2, canvas: Rect, image: &RgbaImage) -> Pos2 {

    Pos2::new(

        // Сначала вычитаем левую границу canvas.
        //
        // Затем делим на ширину canvas.
        // Получаем относительное положение от 0.0 до 1.0.
        //
        // Умножаем на реальную ширину изображения.
        //
        // clamp ограничивает координату границами изображения.
        //
        // Например, если координата вышла за изображение,
        // мы не позволяем ей стать отрицательной или больше ширины.
        ((pos.x - canvas.min.x) / canvas.width() * image.width() as f32)
            .clamp(0.0, image.width() as f32),

        ((pos.y - canvas.min.y) / canvas.height() * image.height() as f32)
            .clamp(0.0, image.height() as f32),
    )
}


// Обратное преобразование.
//
// Эта функция нужна, когда мы знаем координаты в изображении,
// но хотим нарисовать соответствующую область в GUI.
//
// Например, выделение хранится в координатах исходного изображения.
// Чтобы отобразить его поверх масштабированной текстуры,
// необходимо перевести координаты обратно в систему окна.
fn to_screen(pos: Pos2, canvas: Rect, image: &RgbaImage) -> Pos2 {

    Pos2::new(

        // Нормализуем координату изображения
        // и умножаем её на ширину canvas.
        //
        // Затем прибавляем начало canvas,
        // чтобы учесть положение изображения внутри окна.
        canvas.min.x + pos.x / image.width() as f32 * canvas.width(),

        canvas.min.y + pos.y / image.height() as f32 * canvas.height(),
    )
}


// Переводим прямоугольник в целочисленные координаты изображения.
//
// GUI использует f32, потому что координаты интерфейса
// могут находиться между физическими пикселями.
//
// Обработка изображений обычно требует целочисленных координат:
// u32 для X, Y, ширины и высоты.
//
// Поэтому здесь мы преобразуем Rect в:
// (x, y, right, bottom).
fn image_bounds(rect: Rect, image: &RgbaImage) -> (u32, u32, u32, u32) {

    // floor округляет вниз.
    //
    // max(0.0) исключает отрицательные координаты.
    //
    // as u32 переводит число в целочисленный тип.
    //
    // min(image.width()) не позволяет выйти за границы изображения.
    let x = (rect.min.x.floor().max(0.0) as u32).min(image.width());
    let y = (rect.min.y.floor().max(0.0) as u32).min(image.height());


    // Для правой и нижней границ используем ceil.
    //
    // Это важно: если прямоугольник заканчивается между пикселями,
    // ceil позволяет включить крайний частично затронутый пиксель.
    let right = (rect.max.x.ceil().max(0.0) as u32).min(image.width());
    let bottom = (rect.max.y.ceil().max(0.0) as u32).min(image.height());

    (x, y, right, bottom)
}


// ============================================================
// PIXELATION — ПИКСЕЛИЗАЦИЯ ОБЛАСТИ
// ============================================================

// Изменяем изображение по изменяемой ссылке.
//
// &mut RgbaImage означает:
// функция не владеет изображением,
// но получает право временно изменять его.
//
// Почему не передаём RgbaImage напрямую?
//
// Потому что передача значения обычно означает перемещение владения.
// Нам нужно изменить уже существующее изображение,
// не уничтожая и не заменяя объект снаружи.
fn apply_blur(image: &mut RgbaImage, rect: Rect) {

    // Получаем целочисленные границы обрабатываемой области.
    let (x, y, right, bottom) = image_bounds(rect, image);


    // Защита от пустой или некорректной области.
    //
    // Если правая граница не больше левой,
    // либо нижняя не больше верхней,
    // значит обрабатывать нечего.
    //
    // return завершает функцию без ошибки.
    if right <= x || bottom <= y {
        return;
    }


    // Вычисляем ширину и высоту выделенной области.
    let width = right - x;
    let height = bottom - y;


    // crop_imm создаёт представление обрезанной части изображения.
    //
    // to_image() создаёт отдельное изображение из этого фрагмента.
    //
    // Почему мы создаём отдельный буфер?
    //
    // Потому что дальше будем уменьшать и увеличивать изображение.
    // Операции изменения размера должны работать с отдельным результатом,
    // а не менять исходный буфер прямо во время чтения.
    let region = imageops::crop_imm(image, x, y, width, height).to_image();


    // Первый этап пикселизации — уменьшение изображения.
    //
    // Например:
    // область 600x300 превращается примерно в 50x25.
    //
    // Деление на 12 задаёт степень пикселизации.
    // Чем меньше итоговый размер, тем крупнее будут пиксели.
    //
    // max(1) гарантирует, что размер не станет нулевым.
    // Изображение шириной 5 пикселей не должно получить ширину 0.
    //
    // FilterType::Nearest использует ближайший пиксель,
    // не сглаживая переходы между цветами.
    //
    // Это важно для эффекта пикселизации.
    let small = imageops::resize(
        &region,
        (width / 12).max(1),
        (height / 12).max(1),
        imageops::FilterType::Nearest,
    );


    // Второй этап — растягиваем уменьшенное изображение обратно
    // до первоначального размера выделенной области.
    //
    // В результате маленькие цветовые блоки становятся заметными
    // крупными квадратными пикселями.
    let blurred = imageops::resize(
        &small,
        width,
        height,
        imageops::FilterType::Nearest,
    );


    // replace заменяет область исходного изображения
    // обработанным изображением.
    //
    // x и y переводим в i64, потому что replace принимает
    // координаты вставки именно такого типа.
    imageops::replace(image, &blurred, x as i64, y as i64);
}


// ============================================================
// RENDER RESULT — ФОРМИРОВАНИЕ ИТОГОВОГО ИЗОБРАЖЕНИЯ
// ============================================================

// Функция собирает окончательный результат.
//
// Важный принцип архитектуры:
// мы не меняем app.image во время редактирования.
//
// Вместо этого создаём копию исходника и применяем изменения
// к этой копии.
//
// Это позволяет:
//
/*
    1. Не портить оригинальный скриншот.
    2. Повторно сформировать результат.
    3. Не накапливать искажения от повторного изменения размера.
    4. Хранить области пикселизации отдельно от пикселей изображения.
*/

// &RustShot — неизменяемая ссылка.
// Функция читает состояние приложения, но не изменяет его.
fn render_result(app: &RustShot) -> Result<RgbaImage, String> {

    // clone() создаёт независимую копию изображения.
    //
    // Это не просто копирование указателя:
    // RgbaImage владеет пиксельным буфером,
    // поэтому clone() копирует и его содержимое.
    //
    // Для больших изображений это требует дополнительной памяти.
    // Здесь это осознанный компромисс ради сохранения оригинала.
    let mut result = app.image.clone();


    // Перебираем все области пикселизации.
    //
    // &app.blur_areas означает, что мы не забираем Vec из приложения,
    // а только временно заимствуем его для чтения.
    //
    // area имеет тип &Rect.
    //
    // Rect реализует Copy, поэтому *area копирует прямоугольник
    // и передаёт его функции apply_blur.
    for area in &app.blur_areas {
        apply_blur(&mut result, *area);
    }


    // Если выбран режим Area, необходимо обрезать результат.
    if app.mode == Mode::Area {

        // selection — Option<Rect>.
        //
        // ok_or превращает отсутствие выделения в ошибку.
        // ? автоматически возвращает её из функции.
        //
        // Если выделение отсутствует, программа не пытается
        // обрезать изображение по несуществующим координатам.
        let selection = app.selection.ok_or("Select an area first")?;


        // Переводим выделение в целочисленные границы.
        let (x, y, right, bottom) = image_bounds(selection, &result);


        // Проверяем, что область имеет ненулевой размер.
        if right <= x || bottom <= y {
            return Err("Selection is too small".into());
        }


        // Создаём итоговое изображение, обрезанное по выделению.
        //
        // Здесь происходит перемещение нового изображения в result.
        //
        // Старое значение result больше не нужно,
        // поэтому Rust разрешает заменить его новым.
        result = imageops::crop_imm(
            &result,
            x,
            y,
            right - x,
            bottom - y,
        )
        .to_image();
    }

    Ok(result)
}


