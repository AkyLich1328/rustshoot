// enum позволяет описать набор допустимых вариантов значения.
//
// Вместо хранения режима в виде строки "area" или числа 0/1
// мы используем тип Mode.
//
// Это безопаснее: компилятор не позволит случайно передать
// неизвестный режим вроде "something_else".
//
// Copy:
// Значение можно копировать без явного clone().
//
// Clone:
// Позволяет создавать копию значения.
//
// PartialEq:
// Позволяет сравнивать значения через == и !=.
//
// Эти три трейта подходят, потому что наши перечисления
// содержат только небольшие значения без динамической памяти.
#[derive(Clone, Copy, PartialEq)]
enum Mode {
    // Пользователь выбирает прямоугольную область экрана.
    Area,

    // Пользователь обрабатывает весь экран.
    Full,
}


// Куда отправлять готовое изображение.
#[derive(Clone, Copy, PartialEq)]
enum Destination {
    Clipboard,
    Pictures,
}


// Активный инструмент редактора.
#[derive(Clone, Copy, PartialEq)]
enum Tool {
    Select,
    Blur,
}


